import { expect, test, type Page } from '@playwright/test'

async function navigate(page: Page, name: string) {
  const menu = page.getByRole('button', { name: 'Menü öffnen', exact: true })
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
}
async function createGym(page: Page) {
  await page.getByRole('button', { name: 'Training starten', exact: true }).click()
  await page.getByLabel('Trainingstitel', { exact: true }).fill('Kraft am Montag')
  await page.getByLabel('Datum', { exact: true }).fill('2026-10-05')
  await page.getByLabel('Übung 1', { exact: true }).fill('Kniebeugen')
  await page.getByLabel('Übung 1, Satz 1, Gewicht', { exact: true }).fill('42.5')
  await page.getByLabel('Übung 1, Satz 1, Wiederholungen', { exact: true }).fill('8')
  await page.getByLabel('Trainingsnotizen (optional)', { exact: true }).fill('Gute Technik')
}
test.beforeEach(async ({ page }) => {
  await page.goto('./')
  await navigate(page, 'Fitness')
})
test('create, reload, edit and delete a gym workout', async ({ page }) => {
  await createGym(page)
  await page.getByRole('button', { name: 'Training speichern', exact: true }).click()
  await expect(page.getByText('Training auf diesem Gerät gespeichert.', { exact: true })).toBeVisible()
  await page.reload(); await navigate(page, 'Fitness')
  await expect(page.getByText('Kraft am Montag', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Training Kraft am Montag bearbeiten', exact: true }).click()
  await expect(page.getByLabel('Übung 1, Satz 1, Gewicht', { exact: true })).toHaveValue('42.5')
  await expect(page.getByLabel('Datum', { exact: true })).toHaveValue('2026-10-05')
  await page.getByLabel('Übung 1, Satz 1, Gewicht', { exact: true }).fill('45')
  await page.getByRole('button', { name: 'Training speichern', exact: true }).click()
  await expect(page.locator('.history-item')).toHaveCount(1)
  await page.reload(); await navigate(page, 'Fitness')
  await page.getByRole('button', { name: 'Training Kraft am Montag bearbeiten', exact: true }).click()
  await expect(page.getByLabel('Übung 1, Satz 1, Gewicht', { exact: true })).toHaveValue('45')
  await page.getByRole('button', { name: 'Training schließen und Entwurf behalten', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Entwurf verwerfen', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Training Kraft am Montag löschen', exact: true }).click()
  await page.reload(); await navigate(page, 'Fitness')
  await expect(page.locator('.history-item')).toHaveCount(0)
})
test('recover a draft after navigation and reload; cancelled replacement preserves it', async ({ page }) => {
  await createGym(page)
  await navigate(page, 'Übersicht'); await navigate(page, 'Fitness')
  await page.getByRole('button', { name: 'Entwurf fortsetzen' }).click()
  await expect(page.getByLabel('Übung 1, Satz 1, Gewicht', { exact: true })).toHaveValue('42.5')
  await page.reload(); await navigate(page, 'Fitness')
  await page.getByRole('button', { name: 'Entwurf fortsetzen' }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'Laufen', exact: true }).click()
  await expect(page.getByLabel('Trainingstitel', { exact: true })).toHaveValue('Kraft am Montag')
})
test('save all endurance sports and filter history', async ({ page }) => {
  for (const sport of ['Radfahren', 'Laufen', 'Schwimmen']) {
    await page.getByRole('button', { name: sport, exact: true }).click()
    await page.getByLabel('Distanz (km)', { exact: true }).fill(sport === 'Schwimmen' ? '0.5' : '5')
    await page.getByLabel('Höhenmeter (optional)', { exact: true }).fill('20')
    await page.getByLabel('Belastung 1–10 (optional)', { exact: true }).fill('6')
    await page.getByRole('button', { name: 'Training speichern', exact: true }).click()
  }
  await expect(page.locator('.history-item')).toHaveCount(3)
  await page.getByLabel('Sportart filtern', { exact: true }).selectOption('Schwimmen')
  await expect(page.locator('.history-item')).toHaveCount(1)
  await page.getByRole('button', { name: 'Training Schwimmen bearbeiten', exact: true }).click()
  await expect(page.getByLabel('Distanz (km)', { exact: true })).toHaveValue('0.5')
  await expect(page.getByLabel('Belastung 1–10 (optional)', { exact: true })).toHaveValue('6')
})
test('export and restore a backup without duplicating existing entries', async ({ page }, testInfo) => {
  await createGym(page); await page.getByRole('button', { name: 'Training speichern', exact: true }).click()
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Daten exportieren', exact: true }).click()
  const file = testInfo.outputPath('backup.json'); await (await pending).saveAs(file)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Training Kraft am Montag löschen', exact: true }).click()
  await page.getByLabel('Trainingssicherung', { exact: true }).setInputFiles(file)
  await expect(page.locator('.history-item')).toHaveCount(1)
  await page.getByLabel('Trainingssicherung', { exact: true }).setInputFiles(file)
  await expect(page.getByText(/0 Trainings importiert/)).toBeVisible()
  await expect(page.locator('.history-item')).toHaveCount(1)
  await page.getByLabel('Trainingssicherung', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('[{"id":"broken"}]') })
  await expect(page.getByRole('alert')).toContainText('keine gültigen Trainingsdaten')
  await expect(page.locator('.history-item')).toHaveCount(1)
})
test('validation keeps the draft open and narrow layouts do not overflow', async ({ page }) => {
  await createGym(page)
  await page.getByLabel('Dauer (Min.)', { exact: true }).fill('-5')
  await page.getByRole('button', { name: 'Training speichern', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Dauer')
  await expect(page.getByLabel('Trainingstitel', { exact: true })).toHaveValue('Kraft am Montag')
  for (const width of [320, 390, 1280]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})
test('rest timer pauses, resumes and completes even after a long clock jump', async ({ page }) => {
  await page.clock.install()
  await page.getByRole('button', { name: 'Training starten', exact: true }).click()
  await page.getByRole('button', { name: '90 Sek. Pause', exact: true }).click()
  await page.clock.runFor(1000)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const paused = await page.locator('.rest-timer strong').textContent()
  await page.clock.runFor(5000)
  await expect(page.locator('.rest-timer strong')).toHaveText(paused ?? '')
  await page.getByRole('button', { name: 'Fortsetzen', exact: true }).click()
  await page.clock.fastForward(100000)
  await expect(page.getByText('Pause beendet', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Neu starten', exact: true })).toBeVisible()
})
test('installed app reloads offline and keeps saved workouts', async ({ page, context }) => {
  await createGym(page)
  await page.getByRole('button', { name: 'Training speichern', exact: true }).click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload(); await navigate(page, 'Fitness')
  await context.setOffline(true)
  await page.reload(); await navigate(page, 'Fitness')
  await expect(page.getByText('Kraft am Montag', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Training Kraft am Montag bearbeiten', exact: true }).click()
  await page.getByLabel('Übung 1, Satz 1, Gewicht', { exact: true }).fill('47.5')
  await page.getByRole('button', { name: 'Training speichern', exact: true }).click()
  await context.setOffline(false)
  await page.reload(); await navigate(page, 'Fitness')
  await page.getByRole('button', { name: 'Training Kraft am Montag bearbeiten', exact: true }).click()
  await expect(page.getByLabel('Übung 1, Satz 1, Gewicht', { exact: true })).toHaveValue('47.5')
})
test('unavailable browser storage shows an error instead of crashing', async ({ page }) => {
  await page.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('unavailable') } }) })
  await page.reload(); await navigate(page, 'Fitness')
  await expect(page.getByRole('alert').filter({ hasText: 'Trainingsspeicher' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Training starten', exact: true })).toBeDisabled()
})
